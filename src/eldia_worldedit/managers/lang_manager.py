class LangManager:
    """Renders localized messages for 'en' and 'th'."""

    def __init__(self, language: str = "en") -> None:
        self.language = language.lower() if language.lower() in SUPPORTED_LANGUAGES else "en"

    def set_language(self, language: str) -> str:
        norm = language.strip().lower()
        if norm not in SUPPORTED_LANGUAGES:
            raise ValueError(f"Unsupported language '{language}'. Use 'en' or 'th'.")
        self.language = norm
        return norm

    def t(self, key: str, **kwargs: object) -> str:
        table = _MESSAGES.get(self.language, _MESSAGES["en"])
        template = table.get(key) or _MESSAGES["en"].get(key) or key
        if kwargs:
            return template.format(**kwargs)
        return template
